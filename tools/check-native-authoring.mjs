import assert from 'node:assert/strict';
import {execFile} from 'node:child_process';
import fs from 'node:fs/promises';
import path from 'node:path';
import {promisify} from 'node:util';
import {createAsset} from '../prototype/asset-documents.js';
import {activeInstalledVersions} from './install-editor.mjs';
import {nativeEditorSession} from './native-editor-session.mjs';
import {createProject} from './project-manifest.mjs';
import {retainTestEvidence} from './test-artifacts.mjs';

const root=path.resolve(import.meta.dirname,'..');
assert.deepEqual(await activeInstalledVersions('C:/Users/kirby/HBEngine'),[]);
const work=await fs.mkdtemp(path.join(root,'native/build/native-authoring-'));
retainTestEvidence(work);
process.env.HB_USER_DATA_DIR=path.join(work,'UserData');
const project=await createProject('NativeAuthoring',work,'3d');
const material='Assets/Materials/PM_Native.hbphysicalmaterial.json';
const blueprint='Assets/Blueprints/BP_Garden.hbblueprint.json';
const graphMaterial='Assets/Materials/Moss_stone.hbmaterial.json';
await project.project.write(material,JSON.stringify(createAsset('physicalmaterial','검사 머테리얼')));
await project.project.mkdir('Assets/Empty/Sub');
const dispatch=nativeEditorSession();
await dispatch('project.open',{file:project.file});
assert.ok((await dispatch('project.recent')).some(row=>row.file===project.file));
const created=await dispatch('content.create',{folder:'Assets/Materials',kind:'physicalmaterial',name:'PM_새에셋'});
assert.equal(created.path,'Assets/Materials/PM_새에셋.hbphysicalmaterial.json');
assert.ok((await dispatch('content.list',{folder:'Assets'})).entries.some(row=>row.path==='Assets/Empty'));
assert.ok((await dispatch('content.list',{folder:'Assets',query:'pm_native'})).entries.some(row=>row.path===material));
const original=await dispatch('document.open',{path:material});
const operation={op:'replace',path:'/friction',value:.85};
const preview=await dispatch('document.patch',{operations:[operation],expectedRevision:original.revision,dryRun:true});
assert.equal(preview.data.friction,.85);
assert.equal((await dispatch('document.read')).revision,original.revision);
const modified=await dispatch('document.patch',{operations:[operation],expectedRevision:original.revision});
await assert.rejects(dispatch('document.save',{expectedRevision:original.revision}),{code:'REVISION_CONFLICT'});
const outside=JSON.parse(original.text);outside.density=2;
await project.project.write(material,JSON.stringify(outside));
await assert.rejects(dispatch('document.save',{expectedRevision:modified.revision}),{status:409});
assert.deepEqual(JSON.parse(await fs.readFile(path.join(project.root,material),'utf8')),outside);
const report=path.join(work,'report.json');
const executable=path.resolve(process.argv[2] || path.join(root,'dist/HBEngine/HBEngine.exe'));
try {
  await promisify(execFile)(executable,['--native-editor','--smoke-test',report,project.file],{windowsHide:true,timeout:90000});
} catch (error) {
  const log=await fs.readFile(report+'.error.txt','utf8').catch(()=>error.message);
  throw Error(log,{cause:error});
}
const evidence=JSON.parse(await fs.readFile(report,'utf8'));
assert.equal(evidence.webview,false);
assert.equal(evidence.saved,true);
assert.equal(evidence.blueprintSurface.backend,'D3D12');
assert.equal(evidence.materialSurface.backend,'D3D12');
assert.equal(evidence.assetSurface.backend,'D3D12');
await assert.rejects(fs.stat(path.join(process.env.HB_USER_DATA_DIR,'WebView2')),{code:'ENOENT'});
const read=async file=>JSON.parse(await fs.readFile(path.join(project.root,file),'utf8'));
const result=await read(blueprint), moved=result.nodes.find(node=>node.position.x===452&&node.position.y===356);
assert.equal(moved?.key,'print');
assert.equal(moved.inputValues.message,'네이티브 그래프 검사');
assert.ok(result.edges.some(edge=>edge.to.node===moved.id));
assert.equal((await read(graphMaterial)).graph.nodes.length,evidence.materialNodes);
assert.equal((await read(material)).friction,.75);
assert.equal((await read(material)).density,2);
console.log(JSON.stringify({...evidence,report}));
